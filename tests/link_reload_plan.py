#!/usr/bin/env python3
"""Writes a C header of hot reload plans for tests/link_reload_tests.c (the
debug link's agent, its reload with plans: docs/debug-link.md#hot-reload),
planned by tools/svlink.py's planner from builds' blobs and maps, as a
debugger plans them (all but the contexts' section, which needs the running
game: the tests compute it at run time from the functions below).

Usage: link_reload_plan.py -o PLANS.h NAME=OLD_BASE:NEW_BASE...

Each BASE is a serval_add_script() build's path without its extension
(BASE.svmap, BASE.svdbg and BASE_script.c beside each other). For each NAME
the header defines, with the builds' pcs (blob offsets):
  NAME_FUNCTIONS[], NAME_FUNCTION_COUNT  the unchanged functions: {old_start,
                       old_end, new_start} (section 1)
  NAME_PLAN[], NAME_PLAN_SIZE  the plan's sections 1, 3, 4, 5 and 6 as
                       RELOAD_PLAN payloads, each after its length (u16)
  NAME_GLOBALS[][2], NAME_ARRAYS[][2], NAME_FIELDS[][2], NAME_OBJECTS[][2] and
                       their _COUNTs: sections 3 to 6's {old, new}
and for each build (by its base's file name, upper-cased):
  <BUILD>_FN_<FUNCTION>_START, _END  a function's first op's pc, and the end
                       of its last op
  <BUILD>_FIELD_<NAME>  an instance field's number
  <BUILD>_CELLS_<NAME>  a RAM array's first cell in the pool
Python 3 standard library only.
"""

import argparse
import os
import re
import struct
import sys

TOOLS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools")
sys.path.insert(0, TOOLS)
import svlink  # noqa: E402


def c_name(name):
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()


def build_of(base):
    return svlink.Build(svlink.blob_of_c(base + "_script.c"), svlink.DebugMaps(base + ".svmap"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-o", "--output", required=True)
    parser.add_argument("pairs", nargs="+", metavar="NAME=OLD_BASE:NEW_BASE")
    args = parser.parse_args()
    out = ["// Generated by tests/link_reload_plan.py (do not edit): hot reload plans from",
           "// tools/svlink.py's planner.", "", "#include \"serval/platform.h\"", ""]
    builds = {}
    for pair in args.pairs:
        name, _, bases = pair.partition("=")
        old_base, _, new_base = bases.partition(":")
        for base in (old_base, new_base):
            if base not in builds:
                builds[base] = build_of(base)
        old, new = builds[old_base], builds[new_base]
        sections = svlink.reload_maps(old, new)
        functions = sections[svlink.SECTION_FUNCTIONS]
        out.append(f"// {os.path.basename(old_base)} -> {os.path.basename(new_base)}")
        body = ", ".join(f"{{{s}u, {e}u, {n}u}}" for s, e, n in functions) or "{0}"
        out.append(f"static const u32 {name}_FUNCTIONS[][3] = {{{body}}};")
        out.append(f"#define {name}_FUNCTION_COUNT {len(functions)}u")
        plan = b"".join(struct.pack("<H", len(p)) + p for p in svlink.plan_frames(sections))
        out.append(f"static const u8 {name}_PLAN[] = {{{', '.join(str(b) for b in plan)}}};")
        out.append(f"#define {name}_PLAN_SIZE {len(plan)}u")
        for title, section, ctype in (("GLOBALS", svlink.SECTION_GLOBALS, "u16"),
                                      ("ARRAYS", svlink.SECTION_ARRAYS, "u16"),
                                      ("FIELDS", svlink.SECTION_FIELDS, "u8"),
                                      ("OBJECTS", svlink.SECTION_OBJECTS, "u16")):
            rows = sections[section]
            body = ", ".join(f"{{{a}u, {b}u}}" for a, b in rows) or "{0, 0}"
            out.append(f"static const {ctype} {name}_{title}[][2] = {{{body}}};")
            out.append(f"#define {name}_{title}_COUNT {len(rows)}u")
        out.append("")
    for base, build in builds.items():
        prefix = c_name(os.path.basename(base))
        for function, (start, end, _) in svlink.function_ranges(build).items():
            out.append(f"#define {prefix}_FN_{c_name(function)}_START {start}u")
            out.append(f"#define {prefix}_FN_{c_name(function)}_END {end}u")
        for field in build.maps.svdbg["fields"]:
            out.append(f"#define {prefix}_FIELD_{c_name(field['name'])} {field['number']}u")
        blob = build.blob
        table = 16 + struct.unpack_from("<H", blob, 8)[0] * 32 + struct.unpack_from("<H", blob, 10)[0] * 4
        for entry in build.maps.svdbg["arrays"]:
            if entry["kind"] == "ram":
                first = struct.unpack_from("<I", blob, table + entry["number"] * 8 + 4)[0]
                out.append(f"#define {prefix}_CELLS_{c_name(entry['name'])} {first}u")
        out.append("")
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
