#!/usr/bin/env python3
"""Writes a C header of breakpoint sites for tests/link_vm_tests.c (the debug
link's agent, its VM part), from a test script's debug maps, as a debugger's
planner reads them (docs/debug-link.md#stepping; the maps' format is
docs/lua.md#debug-information).

Usage: link_sites.py SCRIPT.lua BASE.svmap BASE.svdbg -o SITES.h

The header defines, with the maps' pcs (blob offsets):
  SITE_<NAME>          the first statement start on the script's line that
                       ends in "-- @site NAME" (a breakpoint on that line)
  FN_<FUNCTION>[]      every statement start of a function or handler, in pc
  FN_<FUNCTION>_COUNT  order ("Looper:create" is FN_LOOPER_CREATE): step
                       over's sites
  FN_<FUNCTION>_FIRST  its first statement start: step into's site
  LOCAL_<FUNCTION>_<NAME>  a local's slot (the cell at fp + slot)
  STATEMENTS[], STATEMENT_COUNT  every statement start of the script
  FUNCTIONS[], FUNCTION_COUNT  each function's pc range (its first and last
                       ops) and statement starts: the function a pc is in
  CALLS[], CALL_COUNT  {statement start, the first statement of a function
                       it calls}: step into's sites (from the listing's CALLs)

The maps are joined by tools/check-debug-maps.py's Maps, the debugger's
reading. Python 3 standard library only.
"""

import argparse
import importlib.util
import json
import os
import re
import sys

TOOLS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools")


def load_maps_module():
    spec = importlib.util.spec_from_file_location("check_debug_maps",
                                                  os.path.join(TOOLS, "check-debug-maps.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def c_name(name):
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("script")
    parser.add_argument("svmap")
    parser.add_argument("svdbg")
    parser.add_argument("-o", "--output", required=True)
    args = parser.parse_args()
    maps_module = load_maps_module()
    with open(args.svmap, encoding="utf-8") as f:
        svmap = json.load(f)
    with open(args.svdbg, encoding="utf-8") as f:
        svdbg = json.load(f)
    maps = maps_module.Maps(svmap, svdbg)

    # Statement starts: (pc, script line, function entry).
    starts = []
    for listing, (_, line, _, start) in sorted(maps.place.items()):
        if start and listing in maps.pc_of_line:
            pc = maps.pc_of_line[listing]
            starts.append((pc, line, maps.function(pc)))
    starts.sort(key=lambda s: s[0])

    out = [f"// Generated by tests/link_sites.py from {os.path.basename(args.script)}'s maps "
           "(do not edit).", "", "#include \"serval/platform.h\"", ""]
    problems = []
    with open(args.script, encoding="utf-8") as f:
        for number, text in enumerate(f, 1):
            m = re.search(r"--\s*@site\s+([A-Z0-9_]+)\s*$", text)
            if not m:
                continue
            pcs = [pc for pc, line, _ in starts if line == number]
            if not pcs:
                problems.append(f"{args.script}:{number}: @site {m.group(1)} has no statement start")
                continue
            out.append(f"#define SITE_{m.group(1)} {pcs[0]}u // line {number}")
    out.append("")
    for entry in svdbg["functions"]:
        name = c_name(entry["name"])
        pcs = [pc for pc, _, fn in starts if fn is entry]
        if not pcs:
            continue
        out.append(f"static const u32 FN_{name}[] = {{{', '.join(f'{pc}u' for pc in pcs)}}};")
        out.append(f"#define FN_{name}_COUNT {len(pcs)}u")
        out.append(f"#define FN_{name}_FIRST {pcs[0]}u")
    out.append("")
    for local in svdbg["locals"]:
        function = c_name(svdbg["functions"][local["function"]]["name"])
        out.append(f"#define LOCAL_{function}_{c_name(local['name'])} {local['slot']}u")
    out.append("")
    out.append(f"static const u32 STATEMENTS[] = {{{', '.join(f'{pc}u' for pc, _, _ in starts)}}};")
    out.append(f"#define STATEMENT_COUNT {len(starts)}u")
    out.append("")

    # Functions: the pcs of their first and last ops, and their statements.
    rows, firsts = [], {}
    for entry in svdbg["functions"]:
        pcs = [pc for pc, line in svmap["pcs"] if entry["first"] <= line <= entry["last"]]
        statements = [pc for pc, _, fn in starts if fn is entry]
        if not pcs or not statements:
            continue
        name = c_name(entry["name"])
        rows.append(f"    {{{pcs[0]}u, {pcs[-1]}u, FN_{name}, FN_{name}_COUNT}},")
        firsts[entry["first"]] = statements[0]
    out.append("typedef struct {")
    out.append("    u32 first, last;        // its first and last ops' pcs")
    out.append("    const u32* statements; // its statement starts")
    out.append("    u32 count;")
    out.append("} SiteFunction;")
    out.append("static const SiteFunction FUNCTIONS[] = {")
    out += rows
    out.append("};")
    out.append(f"#define FUNCTION_COUNT {len(rows)}u")
    out.append("")

    # Calls: each CALL in the listing, by the statement it is part of.
    listing_path = os.path.join(os.path.dirname(args.svmap),
                                os.path.splitext(os.path.basename(args.svmap))[0] + ".svm")
    if not os.path.exists(listing_path):
        listing_path = svmap["listing"]
    with open(listing_path, encoding="utf-8") as f:
        listing = f.read().splitlines()
    labels = {}
    for number, text in enumerate(listing, 1):
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):", text)
        if m:
            labels[m.group(1)] = number
    start_lines = sorted((maps.listing_line(pc), pc) for pc, _, _ in starts)
    calls = []
    for number, text in enumerate(listing, 1):
        m = re.match(r"^\s+CALL\s+([A-Za-z_][A-Za-z0-9_]*)", text)
        if not m or m.group(1) not in labels:
            continue
        statement = max((pc for line, pc in start_lines if line <= number), default=None)
        callee = firsts.get(labels[m.group(1)])
        if statement is not None and callee is not None:
            calls.append(f"    {{{statement}u, {callee}u}},")
    out.append("static const u32 CALLS[][2] = {")
    out += calls
    out.append("};")
    out.append(f"#define CALL_COUNT {len(calls)}u")
    if problems:
        sys.exit("\n".join(problems))
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
