// The stage's own characters (StageDef.cell).
static u16 cell(char c, int mx, int my, u16* front) {
    int half = level_run_left(mx, my) % 2; // which half of a 2-wide piece
    switch (c) {
    case 'T': {
        u16 cell = MT_STUMP;
        if (level_text_at(mx, my - 1) != 'T')
            cell = MT_STUMP_TOP;
        else if (level_text_at(mx, my + 1) != 'T')
            cell = MT_STUMP_BASE;
        return (u16)(cell + half);
    }
    case 'b':
        return (u16)(MT_BUSH + half);
    case 'w':
        *front = (u16)(MT_TALL_GRASS + half);
        return MT_EMPTY;
    case 'f':
        *front = (u16)(MT_FLOWERS + half);
        return MT_EMPTY;
    default:
        return MT_EMPTY;
    }
}

