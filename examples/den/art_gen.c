// art_gen: draws Serval Den's pictures on the host (art_draw.c) and writes
// them as const data, art_data.c and art_data.h, for the ROM (see art.c's
// opening comment).
//
//   art_gen OUT_DIR                  writes OUT_DIR/art_data.c and .h
//   art_gen OUT_DIR --check SRC_DIR  the same, then exits 1 if they differ
//                                    from SRC_DIR's (CTest den_art_data)

#include "art_internal.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define REFRESH "cmake --build --preset host --target den_art_data_refresh"

static const char* const sprite_names[SPRITE_COUNT] = {
    "SPR_KITTEN", "SPR_YOUNG",  "SPR_ADULT",  "SPR_SUN",   "SPR_MOON",  "SPR_LAMP",
    "SPR_DROP",   "SPR_BOWL",   "SPR_ZZZ",    "SPR_HEART", "SPR_SPARK", "SPR_TOMB",
    "SPR_ICON",   "SPR_CURSOR", "SPR_PANEL",  "SPR_STRIP", "SPR_BAR",   "SPR_YARN",
    "SPR_THREAD", "SPR_PAW",    "SPR_BRANCH", "SPR_NEST",
};

static const char* size_name(int size) {
    switch (size) {
    case SPRITE_8x8:
        return "SPRITE_8x8";
    case SPRITE_16x8:
        return "SPRITE_16x8";
    case SPRITE_16x16:
        return "SPRITE_16x16";
    case SPRITE_32x32:
        return "SPRITE_32x32";
    }
    fprintf(stderr, "art_gen: sprite size %d has no name here\n", size);
    exit(1);
}

#define HEADER                                                                                     \
    "// Generated by art_gen (examples/den/art_gen.c) from art_draw.c: do not edit.\n"             \
    "// To change the art, edit art_draw.c and run\n"                                              \
    "//     " REFRESH "\n"                                                                         \
    "// (art.c's opening comment).\n\n"                                                            \
    "// clang-format off\n\n"

static void tiles(FILE* f, const char* name, const u32* t, int count) {
    fprintf(f, "const u32 %s[%d * 8] = {\n", name, count);
    for (int i = 0; i < count; i++) {
        fprintf(f, "   ");
        for (int w = 0; w < 8; w++)
            fprintf(f, " 0x%08X,", (unsigned)t[i * 8 + w]);
        fprintf(f, " // %d\n", i);
    }
    fprintf(f, "};\n\n");
}

static void metatiles(FILE* f, const char* name, const char* cells, const Metatile* m, int count) {
    fprintf(f, "const Metatile %s[%d] = {\n", name, count);
    for (int i = 0; i < count; i++)
        fprintf(f, "    {{0x%04X, 0x%04X, 0x%04X, 0x%04X}, %u},\n", m[i].se[0], m[i].se[1],
                m[i].se[2], m[i].se[3], m[i].collision);
    fprintf(f, "};\n\n");
    fprintf(f, "const u16 %s[%d] = {", cells, count);
    for (int i = 0; i < count; i++)
        fprintf(f, "%s%d,", i % 16 ? " " : "\n    ", i);
    fprintf(f, "\n};\n\n");
}

static void write_c(FILE* f, const ArtDrawing* a) {
    fprintf(f, HEADER "#include \"art_data.h\"\n\n");
    tiles(f, "art_bg_tiles", a->bg_tiles, a->bg_tile_count);
    metatiles(f, "art_den_metatiles", "art_den_cells", a->den_metatiles, DEN_W * MAP_H);
    metatiles(f, "art_sky_metatiles", "art_sky_cells", a->sky_metatiles, SKY_W * MAP_H);
    metatiles(f, "art_tree_metatiles", "art_tree_cells", a->tree_metatiles, TREE_W * MAP_H);
    metatiles(f, "art_csky_metatiles", "art_csky_cells", a->csky_metatiles, TREE_W * MAP_H);
    tiles(f, "art_obj_tiles", a->obj_tiles, a->obj_tile_count);
    fprintf(f, "const SpriteAsset art_sprites[SPRITE_COUNT] = {\n");
    for (int i = 0; i < SPRITE_COUNT; i++) {
        const SpriteAsset* s = &a->sprites[i];
        if (s->tiles_per_frame || s->order_length || s->origin_x || s->origin_y || s->flags ||
            s->frame_times || s->frame_order) {
            fprintf(stderr, "art_gen: %s sets a field art_gen doesn't write\n", sprite_names[i]);
            exit(1);
        }
        fprintf(f,
                "    [%s] = {.tiles = art_obj_tiles + %d * 8, .size = %s, .frame_count = %u, "
                ".palette_slot = %u},\n",
                sprite_names[i], (int)(s->tiles - a->obj_tiles) / 8, size_name(s->size),
                s->frame_count, s->palette_slot);
    }
    fprintf(f, "};\n");
}

static void write_h(FILE* f, const ArtDrawing* a) {
    fprintf(f, HEADER);
    fprintf(f, "#ifndef DEN_ART_DATA_H\n#define DEN_ART_DATA_H\n\n#include \"art_internal.h\"\n\n");
    fprintf(f, "#define ART_BG_TILES %d  // %d bytes\n", a->bg_tile_count, a->bg_tile_count * 32);
    fprintf(f, "#define ART_OBJ_TILES %d // %d bytes\n\n", a->obj_tile_count,
            a->obj_tile_count * 32);
    fprintf(f, "extern const u32 art_bg_tiles[ART_BG_TILES * 8];\n");
    fprintf(f, "extern const Metatile art_den_metatiles[DEN_W * MAP_H];\n");
    fprintf(f, "extern const u16 art_den_cells[DEN_W * MAP_H];\n");
    fprintf(f, "extern const Metatile art_sky_metatiles[SKY_W * MAP_H];\n");
    fprintf(f, "extern const u16 art_sky_cells[SKY_W * MAP_H];\n");
    fprintf(f, "extern const Metatile art_tree_metatiles[TREE_W * MAP_H];\n");
    fprintf(f, "extern const u16 art_tree_cells[TREE_W * MAP_H];\n");
    fprintf(f, "extern const Metatile art_csky_metatiles[TREE_W * MAP_H];\n");
    fprintf(f, "extern const u16 art_csky_cells[TREE_W * MAP_H];\n");
    fprintf(f, "extern const u32 art_obj_tiles[ART_OBJ_TILES * 8];\n");
    fprintf(f, "extern const SpriteAsset art_sprites[SPRITE_COUNT];\n\n");
    fprintf(f, "#endif // DEN_ART_DATA_H\n");
}

static char* slurp(const char* path, long* size) {
    FILE* f = fopen(path, "rb");
    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    *size = ftell(f);
    fseek(f, 0, SEEK_SET);
    char* b = malloc((size_t)*size + 1);
    if (b && fread(b, 1, (size_t)*size, f) != (size_t)*size) {
        free(b);
        b = NULL;
    }
    fclose(f);
    return b;
}

static bool same(const char* a, const char* b) {
    long na, nb;
    char* x = slurp(a, &na);
    char* y = slurp(b, &nb);
    bool ok = x && y && na == nb && memcmp(x, y, (size_t)na) == 0;
    free(x);
    free(y);
    return ok;
}

int main(int argc, char** argv) {
    if (argc != 2 && !(argc == 4 && strcmp(argv[2], "--check") == 0)) {
        fprintf(stderr, "usage: art_gen OUT_DIR [--check SRC_DIR]\n");
        return 2;
    }
    ArtDrawing a;
    art_draw(&a);
    static const char* const names[2] = {"art_data.c", "art_data.h"};
    char path[2][1024];
    for (int i = 0; i < 2; i++) {
        snprintf(path[i], sizeof path[i], "%s/%s", argv[1], names[i]);
        FILE* f = fopen(path[i], "w");
        if (!f) {
            fprintf(stderr, "art_gen: can't write %s\n", path[i]);
            return 1;
        }
        if (i == 0)
            write_c(f, &a);
        else
            write_h(f, &a);
        fclose(f);
    }
    if (argc == 4) {
        for (int i = 0; i < 2; i++) {
            char committed[1024];
            snprintf(committed, sizeof committed, "%s/%s", argv[3], names[i]);
            if (!same(path[i], committed)) {
                fprintf(stderr,
                        "art_gen: %s is not what art_draw.c draws (fresh copy: %s); "
                        "refresh it with: " REFRESH "\n",
                        committed, path[i]);
                return 1;
            }
        }
        printf("art_gen: art_data.c and art_data.h are up to date\n");
    }
    return 0;
}
