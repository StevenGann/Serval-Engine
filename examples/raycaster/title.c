// Where each letter's frame stands when the logo is at rest.
typedef struct {
    u8 frame;   // LOGO_*
    u8 palette; // PAL_WISP or PAL_WARREN
    s16 x, y;
} Letter;
static const Letter letters[] = {
    {LOGO_W, PAL_WISP, 66, 8},     {LOGO_I, PAL_WISP, 88, 8},     {LOGO_S, PAL_WISP, 105, 8},
    {LOGO_P, PAL_WISP, 130, 8},    {LOGO_W, PAL_WARREN, 42, 40},  {LOGO_A, PAL_WARREN, 72, 40},
    {LOGO_R, PAL_WARREN, 98, 40},  {LOGO_R, PAL_WARREN, 123, 40}, {LOGO_E, PAL_WARREN, 146, 40},
    {LOGO_N, PAL_WARREN, 170, 40}, {LOGO_MOON, PAL_WISP, 166, 2},
};
#define LETTERS ((int)(sizeof(letters) / sizeof(letters)[0]))

// A letter drops in from above the screen, goes a little too far and
// settles: how far from its place it is in each of its first frames.
static const s8 drop[] = {-84, -66, -50, -36, -24, -14, -6, 0, 4, 6, 6, 5, 4, 2, 1};
#define DROP_FRAMES ((int)sizeof(drop))
#define LETTER_EVERY 3  // frames between one letter setting off and the next
#define GLINT_EVERY 300 // frames between glints
#define GLINT_FRAMES 4  // a letter is lit this long, and the next follows

int logo_frames(void) {
    return (LETTERS - 1) * LETTER_EVERY + DROP_FRAMES;
}

void logo_draw(int time, int leaving) {
    for (int i = 0; i < LETTERS; i++) {
        const Letter* l = &letters[i];
        int t = time - i * LETTER_EVERY;
        if (t < 0)
            continue;
        int y = l->y;
        u32 palette = l->palette;
        u32 frame = l->frame;
        if (t < DROP_FRAMES) {
            y += drop[t];
        } else {
            // WISP floats, a slow wave along the word; WARREN and the moon
            // stand. Now and then a glint of light crosses the letters.
            if (palette == PAL_WISP && frame != LOGO_MOON)
                y += fx_sin((u16)(time * 400 + i * 9000)) * 2 / FX_ONE;
            int glint = (time - logo_frames()) % GLINT_EVERY - i * GLINT_FRAMES;
            if (glint >= 0 && glint < GLINT_FRAMES && frame != LOGO_MOON)
                palette = PAL_GLINT;
        }
        if (frame == LOGO_I && (time >> 3 & 1))
            frame = LOGO_I_FLICKER;
        if (leaving) {
            // Up and away, faster and faster, one after another.
            int up = leaving - i;
            if (up > 0)
                y -= up * up;
        }
        if (y > -32)
            sprite_draw(SPR_LOGO, (u8)frame, l->x, y, SPRITE_PALETTE(palette));
    }
}

