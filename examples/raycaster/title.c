// What the title, the menu and the results are drawn with (game.h): the
// logo, two fonts and the text composed from them, the glass band behind the
// menu, and the darker colors the view is shown in behind them.
//
// These screens are sprites over the view: the surface leaves no text layer
// (surface.h). One 8 x 8 sprite per character would run out of the 128
// hardware sprites on the list of controls alone, so text is composed. A line
// is drawn with a font into sprite frames 32 pixels wide, as many as it is
// long (a Label), in RAM; the frames reach video memory when their sprite
// group loads, or, for a line that changes while it shows, through
// sprite_set_tiles(). A line then costs a hardware sprite per 32 pixels,
// whatever it says.
//
// The surface leaves sprites 512 tiles, and the HUD's group stays loaded, so
// there are two groups here, never loaded together: the title's (the logo,
// PRESS START, a line of the story) and the menu's and results' (words,
// lines, the band, the cursor).

#include "game.h"

