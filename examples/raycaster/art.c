// A base color's number from its character.
static u8 base_color(char c) {
    if (c >= '1' && c <= '9')
        return (u8)(c - '0');
    if (c >= 'A' && c <= 'V')
        return (u8)(c - 'A' + 10);
    return 0; // '.': transparent
}

// One `size` x `size` frame of a picture (its rows start at `rows`), to bytes
// stored column after column. `recolor`: the wisp's three blues become
// the hex wisp's three violets.
static void to_texels(u8* out, const char* const* rows, int size, bool recolor) {
    for (int x = 0; x < size; x++) {
        for (int y = 0; y < size; y++) {
            u8 c = base_color(rows[y][x]);
            if (recolor && c >= 22 && c <= 24)
                c = (u8)(c + 5);
            *out++ = c;
        }
    }
}

static u32 hex(char c) {
    if (c >= '1' && c <= '9')
        return (u32)(c - '0');
    if (c >= 'A' && c <= 'F')
        return (u32)(c - 'A' + 10);
    return 0;
}

// `frames` frames of a sprite `w` x `h` pixels, one after another in `rows`,
// to 4bpp tiles: frame by frame, each frame's tiles row by row.
static void to_tiles(u32* out, const char* const* rows, int w, int h, int frames) {
    for (int f = 0; f < frames; f++) {
        for (int ty = 0; ty < h / 8; ty++) {
            for (int tx = 0; tx < w / 8; tx++) {
                for (int y = 0; y < 8; y++) {
                    const char* row = rows[f * h + ty * 8 + y] + tx * 8;
                    u32 word = 0;
                    for (int x = 0; x < 8; x++)
                        word |= hex(row[x]) << (4 * x);
                    *out++ = word;
                }
            }
        }
    }
}

#ifdef SERVAL_DEBUG
// Reports a picture whose rows are not all `length` characters: a typo in the
// art above would otherwise show as a sheared picture, or read past a row.
static void check_rows(const char* name, const char* const* rows, int count, int length) {
    for (int y = 0; y < count; y++) {
        int n = 0;
        while (rows[y][n])
            n++;
        if (n != length)
            debug_log(text_format("art: %s row %d is %d characters, not %d", name, y, n, length));
    }
}
#endif

void art_build(void) {
    static const char* const* const walls[TEX_COUNT] = {
        [TEX_STONE] = stone_art, [TEX_MOSS] = moss_art,     [TEX_WOOD] = wood_art,
        [TEX_BRICK] = brick_art, [TEX_BANNER] = banner_art, [TEX_DOOR] = door_art,
        [TEX_LOCK] = lock_art,   [TEX_GATE] = gate_art,
    };
#ifdef SERVAL_DEBUG
    for (int i = 0; i < TEX_COUNT; i++)
        check_rows("a wall", walls[i], TEX_SIZE, TEX_SIZE);
    check_rows("the wisp", wisp_art, 6 * PIC_SIZE, PIC_SIZE);
    check_rows("the things", thing_art, (PIC_COUNT - PIC_FLASK) * PIC_SIZE, PIC_SIZE);
    check_rows("the wand", wand_art, 3 * 64, 32);
    check_rows("the glyphs", glyph_art, 17 * 16, 8);
    check_rows("the icons", icon_art, 3 * 16, 16);
    check_rows("the crosshair", cross_art, 8, 8);
#endif
    for (int i = 0; i < TEX_COUNT; i++)
        to_texels(wall_texels[i], walls[i], TEX_SIZE, false);
    for (int f = 0; f < 6; f++) {
        to_texels(pic_texels[PIC_WISP + f], wisp_art + f * PIC_SIZE, PIC_SIZE, false);
        to_texels(pic_texels[PIC_HEX + f], wisp_art + f * PIC_SIZE, PIC_SIZE, true);
    }
    for (int f = 0; f < PIC_COUNT - PIC_FLASK; f++)
        to_texels(pic_texels[PIC_FLASK + f], thing_art + f * PIC_SIZE, PIC_SIZE, false);

    // Where each column of each picture is opaque.
    for (int p = 0; p < PIC_COUNT; p++) {
        for (int x = 0; x < PIC_SIZE; x++) {
            const u8* column = pic_texels[p] + x * PIC_SIZE;
            u8 from = 0, to = PIC_SIZE;
            while (from < PIC_SIZE && !column[from])
                from++;
            while (to > from && !column[to - 1])
                to--;
            pic_spans[p][x * 2] = from;
            pic_spans[p][x * 2 + 1] = to;
        }
    }

    to_tiles(sprite_tiles + T_WAND * 8, wand_art, 32, 64, 3);
    to_tiles(sprite_tiles + T_GLYPH * 8, glyph_art, 8, 16, 17);
    to_tiles(sprite_tiles + T_ICON * 8, icon_art, 16, 16, 3);
    to_tiles(sprite_tiles + T_CROSS * 8, cross_art, 8, 8, 1);

    // The surface's colors: each base color at each level, plain and red.
    for (u32 level = 0; level < SHADES; level++) {
        for (u32 base = 0; base < 32; base++) {
            Color c = color_mix(0, base_colors[base], level_light[level]);
            surface_colors[TINT_NONE][SHADE(level) | base] = c;
            surface_colors[TINT_HURT][SHADE(level) | base] =
                base ? color_mix(c, HURT_COLOR, HURT_AMOUNT) : 0;
        }
    }
    // Color 0 is the backdrop, which shows only at the edges of a turned or
    // shrunk surface, never in this game; it turns red with the rest.
    surface_colors[TINT_HURT][0] = color_mix(0, HURT_COLOR, HURT_AMOUNT);
}

const Color* art_palette(u32 tint) {
    return surface_colors[tint < TINT_COUNT ? tint : TINT_NONE];
}

