// The game's graphics, all written as ASCII art and converted when the game
// boots (art_build), as the other examples' are; a real project would let
// its editor convert image files at build time.
//
// Two kinds of picture:
//   - What the view draws on the pixel surface: the wall textures and the
//     things' pictures, all 64 x 64. One character per texel names one of 31
//     base colors ('.' is 0: transparent, in pictures): '1'-'9' are 1-9 and
//     'A'-'V' are 10-31. They are stored one byte per texel, column after
//     column (view.c draws columns).
//   - The HUD's sprites, drawn by the hardware over the surface: 4 bits per
//     pixel, '1'-'9' and 'A'-'F' for the 15 colors of the sprite's palette.
// A picture's frames follow one another in its array, each under a comment.
// Everything is lit from the top left.

#include "game.h"

