// Sprite tiles, in the order of the sprites below.
#define T_WAND 0                  // 3 frames of 32x64: 32 tiles each
#define T_GLYPH (T_WAND + 3 * 32) // 17 frames of 8x16
#define T_ICON (T_GLYPH + 17 * 2) // 3 frames of 16x16
#define T_CROSS (T_ICON + 3 * 4)  // 8x8
